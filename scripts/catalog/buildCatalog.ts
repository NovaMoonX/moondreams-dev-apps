/*
 * Expands scripts/catalog/catalogSource.ts into the typed catalog under src/apps/pinch/catalog.
 * Run `npm run catalog:build`.
 */
import fs from 'node:fs';
import path from 'node:path';

import {
  CATALOG_FAMILY_ROWS,
  CATALOG_INGREDIENT_ROWS,
} from './catalogSource.ts';

const OUT_DIR = path.resolve('src/apps/pinch/catalog');
const UNITS = new Set([
  'G',
  'KG',
  'OZ',
  'LB',
  'ML',
  'L',
  'TSP',
  'TBSP',
  'CUP',
  'FL_OZ',
  'PINCH',
  'EACH',
]);

const toLines = (text: string) =>
  text
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
const toNumber = (value: string) => (value === '-' ? null : Number(value));

const families = toLines(CATALOG_FAMILY_ROWS).map((line) => {
  const [slug, name] = line.split('|');
  return { slug, id: `cat-fam-${slug}`, name };
});
const familyIds = new Set(families.map((family) => family.slug));

const ingredients = toLines(CATALOG_INGREDIENT_ROWS).map((line) => {
  const [
    slug,
    name,
    family,
    kcal,
    protein,
    carbs,
    fat,
    serving,
    gramsPerMl,
    gramsEach,
    aliases,
  ] = line.split('|');
  const [servingAmount, servingUnit] = serving.split(' ');
  const row = {
    id: `cat-${slug}`,
    name,
    familyId: `cat-fam-${family}`,
    aliases: (aliases ?? '')
      .split(',')
      .map((alias) => alias.trim())
      .filter(Boolean),
    per100g: {
      calories: Number(kcal),
      protein: Number(protein),
      carbs: Number(carbs),
      fat: Number(fat),
    },
    serving: { amount: Number(servingAmount), unit: servingUnit },
    gramsPerMl: toNumber(gramsPerMl),
    gramsEach: toNumber(gramsEach),
  };
  const isValid =
    familyIds.has(family) &&
    UNITS.has(servingUnit) &&
    [
      row.per100g.calories,
      row.per100g.protein,
      row.per100g.carbs,
      row.per100g.fat,
      row.serving.amount,
    ].every(Number.isFinite);
  if (!isValid) {
    throw new Error(`Bad catalog row: ${line}`);
  }
  return row;
});

const duplicate = ingredients.find(
  (row, index) =>
    ingredients.findIndex((other) => other.id === row.id) !== index,
);
if (duplicate) {
  throw new Error(`Duplicate catalog id: ${duplicate.id}`);
}

const header =
  '// Generated by scripts/catalog/buildCatalog.ts from scripts/catalog/catalogSource.ts. Edit the source, not this file.\n';

fs.writeFileSync(
  path.join(OUT_DIR, 'catalogFamilies.ts'),
  `${header}import type { CatalogFamily } from '@apps/pinch/types';\n\n// prettier-ignore\nexport const CATALOG_FAMILIES: CatalogFamily[] = [\n${families
    .map(
      (family) => `  ${JSON.stringify({ id: family.id, name: family.name })},`,
    )
    .join('\n')}\n];\n`,
);
fs.writeFileSync(
  path.join(OUT_DIR, 'catalogIngredients.ts'),
  `${header}import type { CatalogIngredient } from '@apps/pinch/types';\n\n// prettier-ignore\nexport const CATALOG_INGREDIENTS: CatalogIngredient[] = [\n${ingredients
    .map((row) => `  ${JSON.stringify(row)},`)
    .join('\n')}\n];\n`,
);
console.log(
  `Wrote ${families.length} families and ${ingredients.length} ingredients.`,
);
